export const ACTIVE_SERVICE_IDS = INTEGRATION_SERVICES.filter(
  (s) => s.envVars.length > 0 && !s.id.includes("-"),
).map((s) => s.id);

export function getServiceById(id: string): IntegrationService | undefined {
  return INTEGRATION_SERVICES.find((s) => s.id === id);
}

export function getAlternativesFor(serviceId: string): IntegrationService[] {
  const service = getServiceById(serviceId);
  if (!service) return [];
  return service.alternatives
    .map((altId) => getServiceById(altId))
    .filter(Boolean) as IntegrationService[];
}

export function getServicesByCategory(category: string): IntegrationService[] {
  return INTEGRATION_SERVICES.filter((s) => s.category === category);
}

